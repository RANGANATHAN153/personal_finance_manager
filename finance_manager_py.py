#expense class (oop)
class Expense:

    def __init__(self, amount, category, date, description):
        self.amount = float(amount)
        self.category = category
        self.date = date
        self.description = description

    def to_list(self):
        return [self.date, self.category, self.amount, self.description]

    def __str__(self):
        return f"{self.date} | {self.category} | ₹{self.amount} | {self.description}"

import csv
import os
from datetime import datetime

FILE_NAME = "/content/expenses.csv"

def load_expenses():

    expenses = []

    if not os.path.exists(FILE_NAME):
        return expenses

    with open(FILE_NAME, "r") as file:
        reader = csv.reader(file)
        next(reader, None)

        for row in reader:
            # Corrected: Assuming CSV is structured as Amount, Category, Date, Description
            # Original: expense = Expense(row[2], row[1], row[0], row[3])
            expense = Expense(row[0], row[1], row[2], row[3])
            expenses.append(expense)

    return expenses


def save_expenses(expenses):

    with open(FILE_NAME, "w", newline="") as file:

        writer = csv.writer(file)

        # Note: save_expenses writes as Date, Category, Amount, Description
        # The fix in load_expenses assumes a different existing file format.
        # To ensure consistency, if saving, it should be in the order load_expenses expects or vice versa.
        # For now, fixing load_expenses to match the file that caused the error.
        writer.writerow(["Date", "Category", "Amount", "Description"])

        for expense in expenses:
            writer.writerow(expense.to_list())

#add expenses
def add_expense(expenses):

    try:
        amount = float(input("Enter amount: "))
        category = input("Enter category: ")
        date = input("Enter date (YYYY-MM-DD): ")
        description = input("Enter description: ")

        expense = Expense(amount, category, date, description)

        expenses.append(expense)

        save_expenses(expenses)

        print("Expense added successfully!")

    except:
        print("Invalid input!")

#view expense
def view_expenses(expenses):

    if not expenses:
        print("No expenses found")
        return

    for expense in expenses:
        print(expense)

#category report
def category_report(expenses):

    report = {}

    for e in expenses:

        if e.category in report:
            report[e.category] += e.amount
        else:
            report[e.category] = e.amount

    print("\nCategory Summary")

    for category, amount in report.items():
        print(category, ":", amount)

#monthly report
def monthly_report(expenses):

    report = {}

    for e in expenses:

        month = e.date[:7]

        if month in report:
            report[month] += e.amount
        else:
            report[month] = e.amount

    print("\nMonthly Expense Report")

    for m, amt in report.items():
        print(m, ":", amt)

#search expenses
def search_expense(expenses):

    keyword = input("Enter keyword: ")

    for e in expenses:

        if keyword.lower() in e.description.lower():
            print(e)

#backup data
def backup_data():

    backup_file = "backup_expenses.csv"

    if os.path.exists(FILE_NAME):

        with open(FILE_NAME, "r") as original:
            data = original.read()

        with open(backup_file, "w") as backup:
            backup.write(data)

        print("Backup created")

#main meny system
def main():

    expenses = load_expenses()

    while True:

        print("\nPERSONAL FINANCE MANAGER")
        print("1 Add Expense")
        print("2 View Expenses")
        print("3 Category Report")
        print("4 Monthly Report")
        print("5 Search Expense")
        print("6 Backup Data")
        print("7 Exit")

        choice = input("Enter choice: ")

        if choice == "1":
            add_expense(expenses)

        elif choice == "2":
            view_expenses(expenses)

        elif choice == "3":
            category_report(expenses)

        elif choice == "4":
            monthly_report(expenses)

        elif choice == "5":
            search_expense(expenses)

        elif choice == "6":
            backup_data()

        elif choice == "7":
            print("Exiting program")
            break

        else:
            print("Invalid choice")

#run program
main()